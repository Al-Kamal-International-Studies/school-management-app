-- The inbox: every chat I'm in, newest first, with my unread count. Direct
-- chats someone else opened but never wrote in are hidden (like WhatsApp).
-- Admins see every subject group, but only once it has messages.
create or replace function public.my_chats()
returns table (
  chat_id uuid,
  kind text,
  cst_id uuid,
  other_id uuid,
  last_message_at timestamptz,
  last_message_preview text,
  last_sender_id uuid,
  unread integer
)
language sql
stable
security definer
set search_path = public
as $$
  with me as (
    select auth.uid() as uid, exists (select 1 from profiles where id = auth.uid() and role = 'admin') as is_admin
  )
  select c.id, c.kind, c.cst_id,
    case when c.kind = 'direct' then case when c.user_a = me.uid then c.user_b else c.user_a end end,
    c.last_message_at, c.last_message_preview, c.last_sender_id,
    (
      select count(*)::int from chat_messages m
      where m.chat_id = c.id and m.sender_id <> me.uid
      and m.created_at > coalesce((select r.read_up_to from chat_receipts r where r.chat_id = c.id and r.user_id = me.uid), '-infinity'::timestamptz)
    )
  from chats c, me
  where me.uid is not null
  and (
    (c.kind = 'direct' and me.uid in (c.user_a, c.user_b) and (c.last_message_at is not null or c.created_by = me.uid))
    or (c.kind = 'group' and public.is_group_member(c.cst_id, me.uid) and (not me.is_admin or c.last_message_at is not null))
  )
  order by c.last_message_at desc nulls last;
$$;

create or replace function public.my_unread_total()
returns integer
language sql
stable
security definer
set search_path = public
as $$
  select coalesce(sum(unread), 0)::int from public.my_chats();
$$;

-- People I can start a chat with, with a short context line (class or
-- subjects) for the contact row.
create or replace function public.my_contacts()
returns table (id uuid, full_name text, role user_role, avatar_url text, context text)
language sql
stable
security definer
set search_path = public
as $$
  select p.id, p.full_name, p.role, p.avatar_url,
    case
      when p.role = 'student' then (select cl.name || ' - ' || cl.section from students s join classes cl on cl.id = s.class_id where s.id = p.id)
      when p.role = 'teacher' then (
        select string_agg(distinct sub.name, ', ')
        from class_subject_teachers cst join subjects sub on sub.id = cst.subject_id
        where cst.teacher_id = p.id
        and (
          (select role from profiles where id = auth.uid()) <> 'student'
          or cst.class_id = (select class_id from students where id = auth.uid())
        )
      )
    end
  from profiles p
  where auth.uid() is not null and public.can_start_chat(auth.uid(), p.id)
  order by case p.role when 'admin' then 0 when 'teacher' then 1 when 'student' then 2 else 3 end, p.full_name;
$$;

-- ----------------------------------------------------------------------------
-- Subject groups: one chat per class_subject_teachers row, kept in sync.
-- ----------------------------------------------------------------------------
create or replace function public.on_cst_insert_create_group()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into chats (kind, cst_id) values ('group', new.id) on conflict (cst_id) do nothing;
  return new;
end;
$$;

create trigger trg_cst_create_group
  after insert on class_subject_teachers
  for each row execute function on_cst_insert_create_group();

insert into chats (kind, cst_id)
select 'group', cst.id from class_subject_teachers cst
on conflict (cst_id) do nothing;

-- ----------------------------------------------------------------------------
-- RLS: members read; nobody writes directly (server + RPCs only).
-- ----------------------------------------------------------------------------
alter table chats enable row level security;
alter table chat_messages enable row level security;
alter table chat_receipts enable row level security;
alter table message_flags enable row level security;

create policy "members can read their chats"
  on chats for select to authenticated using (public.is_chat_member(id, auth.uid()));
create policy "members can read chat messages"
  on chat_messages for select to authenticated using (public.is_chat_member(chat_id, auth.uid()));
create policy "members can read chat receipts"
  on chat_receipts for select to authenticated using (public.is_chat_member(chat_id, auth.uid()));
create policy "admins can read message flags"
  on message_flags for select to authenticated using (is_admin());
create policy "admins can mark message flags reviewed"
  on message_flags for update to authenticated using (is_admin()) with check (is_admin());

revoke execute on function public.open_direct_chat(uuid, uuid) from public, anon, authenticated;
revoke execute on function public.send_chat_message(uuid, uuid, text, uuid) from public, anon, authenticated;
revoke execute on function public.can_send_in_chat(uuid, uuid) from public, anon;
revoke execute on function public.mark_all_delivered() from public, anon;
revoke execute on function public.mark_chat_read(uuid, timestamptz) from public, anon;
revoke execute on function public.my_chats() from public, anon;
revoke execute on function public.my_unread_total() from public, anon;
revoke execute on function public.my_contacts() from public, anon;
grant execute on function public.open_direct_chat(uuid, uuid) to service_role;
grant execute on function public.send_chat_message(uuid, uuid, text, uuid) to service_role;

