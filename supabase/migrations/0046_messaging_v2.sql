-- ============================================================================
-- Messaging v2 (HANDOVER Part 42): one WhatsApp-style inbox for direct chats
-- AND subject groups, with live delivery, delivered/read receipts, and a
-- server-only send path so every message passes the content-safety filter.
--
-- Why a new model instead of extending dm_* / subject_chat_*:
--   * 0 rows existed in either (checked in production 2026-10-28), so there is
--     nothing to migrate; both old tables are left untouched and unused.
--   * The old send path was slow (a server action that awaited push delivery
--     and re-rendered the whole page) and had no receipts at all.
--   * Users could INSERT messages straight through RLS, which would let a
--     crafted client skip the word filter. Here there is NO insert policy:
--     send_chat_message() is executable by service_role only, and the server
--     action runs the filter before calling it.
--
-- Who may message whom (Muhammad, 2026-10-28):
--   * admins (Principal@, muhammad@) -> anyone, any time, any group
--   * teacher -> the students they teach, the parents of those students,
--     and the admins
--   * student -> only the teachers who teach them. Never a classmate, never
--     management — but a student may REPLY in a chat an admin started
--   * parent  -> their children's teachers and the admins (unchanged)
--   * subject groups: one per class_subject_teachers row; members are that
--     teacher + the students currently in the class (+ admins)
--
-- Receipts are per-member watermarks (delivered_up_to / read_up_to), not a
-- row per message: "delivered" = the member's device received everything up
-- to that time, "read" = they opened the chat up to that time. Ticks are
-- derived by comparing a message's created_at with the other members' marks.
-- ============================================================================

create table chats (
  id uuid primary key default gen_random_uuid(),
  kind text not null check (kind in ('direct', 'group')),
  -- direct: the two people, stored in sorted order so a pair has one chat
  user_a uuid references profiles(id) on delete cascade,
  user_b uuid references profiles(id) on delete cascade,
  -- group: the class+subject+teacher it belongs to
  cst_id uuid unique references class_subject_teachers(id) on delete cascade,
  created_by uuid references profiles(id) on delete set null,
  last_message_at timestamptz,
  last_message_preview text,
  last_sender_id uuid references profiles(id) on delete set null,
  created_at timestamptz not null default now(),
  unique (user_a, user_b),
  check (
    (kind = 'direct' and user_a is not null and user_b is not null and user_a < user_b and cst_id is null)
    or (kind = 'group' and cst_id is not null and user_a is null and user_b is null)
  )
);

create index idx_chats_user_a on chats(user_a);
create index idx_chats_user_b on chats(user_b);

create table chat_messages (
  id uuid primary key default gen_random_uuid(),
  chat_id uuid not null references chats(id) on delete cascade,
  sender_id uuid not null references profiles(id) on delete cascade,
  content text not null check (char_length(content) between 1 and 4000),
  -- generated by the sender's browser: makes a retried/double-tapped send a
  -- no-op and lets the optimistic bubble be matched to the stored row
  client_id uuid not null,
  created_at timestamptz not null default clock_timestamp(),
  unique (sender_id, client_id)
);

create index idx_chat_messages_chat on chat_messages(chat_id, created_at);

create table chat_receipts (
  chat_id uuid not null references chats(id) on delete cascade,
  user_id uuid not null references profiles(id) on delete cascade,
  delivered_up_to timestamptz,
  read_up_to timestamptz,
  primary key (chat_id, user_id)
);

-- The safety filter's log, for the admin review page. Written by the server
-- (service role) only. action = 'blocked' (refused, never delivered) or
-- 'flagged' (borderline score: delivered, but a human should look). An
-- admin's verdict ('harmful' / 'ok') doubles as real labelled data for
-- retraining the model (ml/README.md).
create table message_flags (
  id uuid primary key default gen_random_uuid(),
  sender_id uuid references profiles(id) on delete set null,
  chat_id uuid references chats(id) on delete set null,
  message_id uuid references chat_messages(id) on delete set null,
  action text not null check (action in ('blocked', 'flagged')),
  content text not null,
  reasons text[] not null default '{}',
  score real,
  created_at timestamptz not null default now(),
  verdict text check (verdict in ('harmful', 'ok')),
  reviewed_at timestamptz,
  reviewed_by uuid references profiles(id) on delete set null
);

create index idx_message_flags_created on message_flags(created_at desc);

-- ----------------------------------------------------------------------------
-- Membership and permission helpers
-- ----------------------------------------------------------------------------
create or replace function public.is_group_member(p_cst_id uuid, p_user uuid)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (select 1 from profiles where id = p_user and role = 'admin' and is_active and archived_at is null)
    or exists (
      select 1 from class_subject_teachers cst
      where cst.id = p_cst_id
      and (
        cst.teacher_id = p_user
        or exists (select 1 from students s where s.id = p_user and s.class_id = cst.class_id)
      )
    );
$$;

create or replace function public.is_chat_member(p_chat_id uuid, p_user uuid default auth.uid())
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from chats c
    where c.id = p_chat_id
    and (
      (c.kind = 'direct' and p_user in (c.user_a, c.user_b))
      or (c.kind = 'group' and public.is_group_member(c.cst_id, p_user))
    )
  );
$$;

-- Who `a` may START a direct chat with. Both must be active AKIS accounts.
create or replace function public.can_start_chat(a uuid, b uuid)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select a <> b and exists (
    select 1 from profiles pa, profiles pb
    where pa.id = a and pb.id = b
    and pa.is_active and pb.is_active and pa.archived_at is null and pb.archived_at is null
    and exists (select 1 from profile_center_access x where x.profile_id = b and x.center_id = '00000000-0000-0000-0000-000000000001')
    and (
      pa.role = 'admin'
      or (pb.role = 'admin' and pa.role in ('teacher', 'parent'))
      or (pa.role = 'teacher' and pb.role = 'student' and exists (
        select 1 from students s join class_subject_teachers cst on cst.class_id = s.class_id
        where s.id = b and cst.teacher_id = a
      ))
      or (pa.role = 'student' and pb.role = 'teacher' and exists (
        select 1 from students s join class_subject_teachers cst on cst.class_id = s.class_id
        where s.id = a and cst.teacher_id = b
      ))
      or (pa.role = 'teacher' and pb.role = 'parent' and (
        exists (
          select 1 from parent_students ps join students s on s.id = ps.student_id
          join class_subject_teachers cst on cst.class_id = s.class_id
          where ps.parent_id = b and cst.teacher_id = a
        )
        or exists (
          select 1 from parent_students ps join autism_assignments aa on aa.student_id = ps.student_id
          where ps.parent_id = b and aa.teacher_id = a
        )
      ))
      or (pa.role = 'parent' and pb.role = 'teacher' and (
        exists (
          select 1 from parent_students ps join students s on s.id = ps.student_id
          join class_subject_teachers cst on cst.class_id = s.class_id
          where ps.parent_id = a and cst.teacher_id = b
        )
        or exists (
          select 1 from parent_students ps join autism_assignments aa on aa.student_id = ps.student_id
          where ps.parent_id = a and aa.teacher_id = b
        )
      ))
    )
  );
$$;

-- Whether `p_user` may post in this chat right now. Re-checked on every send,
-- so a teacher moved off a class immediately stops being able to message its
-- students (the history stays readable).
create or replace function public.can_send_in_chat(p_chat_id uuid, p_user uuid)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select coalesce((
    select case c.kind
      when 'group' then public.is_group_member(c.cst_id, p_user)
      else p_user in (c.user_a, c.user_b) and (
        public.can_start_chat(p_user, case when c.user_a = p_user then c.user_b else c.user_a end)
        -- replying in a chat the other side was allowed to start (e.g. a
        -- student answering the principal)
        or (
          c.created_by = case when c.user_a = p_user then c.user_b else c.user_a end
          and public.can_start_chat(c.created_by, p_user)
        )
      )
    end
    from chats c where c.id = p_chat_id
  ), false);
$$;

-- ----------------------------------------------------------------------------
-- Server-only write path (service_role). The caller has already authenticated
-- the user and run the content filter.
-- ----------------------------------------------------------------------------
create or replace function public.open_direct_chat(p_me uuid, p_other uuid)
returns uuid
language plpgsql
security definer
set search_path = public
as $$
declare
  v_a uuid := least(p_me, p_other);
  v_b uuid := greatest(p_me, p_other);
  v_id uuid;
begin
  select id into v_id from chats where kind = 'direct' and user_a = v_a and user_b = v_b;
  if v_id is not null then
    if not public.is_chat_member(v_id, p_me) then return null; end if;
    return v_id;
  end if;
  if not public.can_start_chat(p_me, p_other) then
    return null;
  end if;
  insert into chats (kind, user_a, user_b, created_by) values ('direct', v_a, v_b, p_me)
  on conflict (user_a, user_b) do update set user_a = excluded.user_a
  returning id into v_id;
  return v_id;
end;
$$;

create or replace function public.send_chat_message(p_sender uuid, p_chat_id uuid, p_content text, p_client_id uuid)
returns chat_messages
language plpgsql
security definer
set search_path = public
as $$
declare
  v_row chat_messages;
begin
  -- idempotent retry: the same client_id returns the already-stored row
  select * into v_row from chat_messages where sender_id = p_sender and client_id = p_client_id;
  if found then return v_row; end if;

  if not public.can_send_in_chat(p_chat_id, p_sender) then
    raise exception 'not_allowed' using errcode = '42501';
  end if;

  -- flood guard: at most 20 messages per 10 seconds per sender
  if (select count(*) from chat_messages where sender_id = p_sender and created_at > clock_timestamp() - interval '10 seconds') >= 20 then
    raise exception 'rate_limited' using errcode = '54000';
  end if;

  insert into chat_messages (chat_id, sender_id, content, client_id)
  values (p_chat_id, p_sender, p_content, p_client_id)
  returning * into v_row;
  return v_row;
end;
$$;

-- Keeps the chat list's last-message fields current, and marks the sender's
-- own message as delivered+read for them.
create or replace function public.on_chat_message_insert()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  update chats
  set last_message_at = new.created_at, last_message_preview = left(new.content, 140), last_sender_id = new.sender_id
  where id = new.chat_id;

  insert into chat_receipts (chat_id, user_id, delivered_up_to, read_up_to)
  values (new.chat_id, new.sender_id, new.created_at, new.created_at)
  on conflict (chat_id, user_id) do update
  set delivered_up_to = greatest(chat_receipts.delivered_up_to, excluded.delivered_up_to),
      read_up_to = greatest(chat_receipts.read_up_to, excluded.read_up_to);
  return new;
end;
$$;

create trigger trg_chat_message_insert
  after insert on chat_messages
  for each row execute function on_chat_message_insert();

-- ----------------------------------------------------------------------------
-- Receipts (called by the signed-in user's own browser)
-- ----------------------------------------------------------------------------

-- "My device has received everything so far" — across all my chats. Called
-- when the app opens and whenever a new message arrives over Realtime.
create or replace function public.mark_all_delivered()
returns void
language sql
security definer
set search_path = public
as $$
  insert into chat_receipts (chat_id, user_id, delivered_up_to)
  select c.id, auth.uid(), c.last_message_at
  from chats c
  where auth.uid() is not null
  and c.last_message_at is not null
  and public.is_chat_member(c.id, auth.uid())
  and (c.kind = 'direct' or not exists (select 1 from profiles where id = auth.uid() and role = 'admin')
       or exists (select 1 from chat_receipts r where r.chat_id = c.id and r.user_id = auth.uid()))
  on conflict (chat_id, user_id) do update
  set delivered_up_to = excluded.delivered_up_to
  where chat_receipts.delivered_up_to is null or chat_receipts.delivered_up_to < excluded.delivered_up_to;
$$;

-- "I have read this chat up to p_up_to" (also implies delivered).
create or replace function public.mark_chat_read(p_chat_id uuid, p_up_to timestamptz)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_up_to timestamptz := least(p_up_to, clock_timestamp());
begin
  if auth.uid() is null or not public.is_chat_member(p_chat_id, auth.uid()) then
    return;
  end if;
  insert into chat_receipts (chat_id, user_id, delivered_up_to, read_up_to)
  values (p_chat_id, auth.uid(), v_up_to, v_up_to)
  on conflict (chat_id, user_id) do update
  set delivered_up_to = greatest(chat_receipts.delivered_up_to, excluded.delivered_up_to),
      read_up_to = greatest(chat_receipts.read_up_to, excluded.read_up_to)
  where chat_receipts.read_up_to is null or chat_receipts.read_up_to < excluded.read_up_to;
end;
$$;

